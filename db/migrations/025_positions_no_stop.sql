-- ЭТАП 9.2 §4, §5. Версия логики 6: предела убытка НЕТ, срок 48 часов,
-- с 24-го часа — выход при первом достижении чистого плюса.
--
-- ЧТО РЕШЕНО И КЕМ. Этап 9.1.6 ЗАМЕРИЛ пять вариантов правила выхода на
-- фактических позициях. Владелец 07.09.2026 выбрал по числам замера вариант
-- B_nostop_plus_48 и ввёл его в боевой контур. Период накопления версии 5
-- прерван досрочно волей владельца — это осознанное решение, а не упущение.
--
-- ГЛАВНОЕ УСЛОВИЕ ЭТАПА: РАЗДЕЛЕНИЕ ВЕРСИЙ (§1 ТЗ). Позиции версии 6 пишутся
-- В ТУ ЖЕ таблицу positions — новая не создаётся (§9.3 ТЗ). Существующие
-- строки версии 5 НЕ ПЕРЕПИСЫВАЮТСЯ, не пересчитываются и не помечаются
-- заново: ни одной строки. Эта миграция не содержит НИ ОДНОГО UPDATE — только
-- ослабление NOT NULL и новые ограничения, и все они написаны так, чтобы уже
-- лежащие строки версии 5 им удовлетворяли без единой правки.
--
-- ПОЧЕМУ ОСЛАБЛЕНИЕ NOT NULL БЕЗОПАСНО ДЛЯ ВЕРСИИ 5. Снятое NOT NULL заменено
-- ограничением positions_no_stop_chk, которое требует ОБРАТНОГО: при
-- logic_version < 6 stop_pct и stop_price обязаны быть заполнены — то есть для
-- версии 5 поля остаются обязательными ровно как прежде (§4.2 ТЗ). NULL
-- допустим ТОЛЬКО при logic_version >= 6.
--
-- ПОЧЕМУ ПРЕДЕЛ НЕ ХРАНИТСЯ ВЫЧИСЛЕННЫМ (§4.1 ТЗ). Записать stop_pct = 1.0 и
-- никогда его не проверять было бы худшим решением: строка выглядела бы как
-- позиция с пределом, любой запрос «сколько сделок закрыл предел» считал бы её
-- наравне с настоящими, а отличить её было бы нечем. Данные, которые лгут,
-- хуже отсутствующих данных.
--
-- ИСХОД stop ДЛЯ ВЕРСИИ 6 НЕВОЗМОЖЕН ФИЗИЧЕСКИ (§4.4 ТЗ), и записано это
-- ОГРАНИЧЕНИЕМ БАЗЫ, а не обещанием кода: проверка в коде переживает ровно до
-- первой правки, которую забыли прогнать через тесты.
--
-- НОВЫЙ ИСХОД plus_exit (§5.1 ТЗ) — выход в чистый плюс после суток ожидания.
-- Цена выхода при нём равна ЦЕНЕ БЕЗУБЫТКА, а не закрытию бара, поэтому итог
-- такой сделки равен нулю по построению.
--
-- ИМЯ ИСХОДА ПО СРОКУ НЕ МЕНЯЕТСЯ (§5.2 ТЗ). Версия 6 закрывается по сроку тем
-- же 'timeout', что и версия 5. Причина: событие ОДНО И ТО ЖЕ — «срок вышел,
-- закрываем по рынку», — а отличается только сам срок, и он уже записан в
-- строке колонкой deadline_at. Завести 'timeout_48' значило бы завести второе
-- имя для одного события и заставить каждый будущий запрос знать оба; а строки
-- версии 5 переименованию не подлежат (§5.2 ТЗ), так что старое имя из базы
-- всё равно никуда не делось бы. Версии разделяет logic_version, а не словарь.
--
-- Миграция идемпотентна. Откат — 025_positions_no_stop_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/025_positions_no_stop.sql

BEGIN;

-- 1. ОСЛАБЛЕНИЕ NOT NULL (§4.2 ТЗ). DROP NOT NULL идемпотентен сам по себе:
--    повторный вызов на колонке без NOT NULL — не ошибка.
ALTER TABLE positions ALTER COLUMN stop_pct   DROP NOT NULL;
ALTER TABLE positions ALTER COLUMN stop_price DROP NOT NULL;

-- 2. ПЕРЕЧЕНЬ ПРИЧИН ВЫХОДА ПОПОЛНЯЕТСЯ ШЕСТЫМ ЗНАЧЕНИЕМ (§5.1 ТЗ).
--    В PostgreSQL CHECK нельзя расширить на месте: единственный способ — снять
--    и поставить заново (тот же приём, что в миграции 019).
ALTER TABLE positions DROP CONSTRAINT IF EXISTS positions_reason_chk;
ALTER TABLE positions ADD CONSTRAINT positions_reason_chk
    CHECK (exit_reason IS NULL OR exit_reason IN
           ('target', 'stop', 'timeout', 'ambiguous', 'data_gap', 'plus_exit'));

-- 3. ГРАНИЦЫ ЧИСЕЛ. Прежний positions_bounds_chk требовал stop_pct > 0
--    безусловно; при NULL это условие даёт NULL, и строка версии 6 прошла бы
--    (CHECK отвергает только FALSE). Полагаться на это нельзя: правило,
--    выполняющееся по случайности трёхзначной логики, читается как ошибка и
--    однажды будет «исправлено». Условие переписано явно.
ALTER TABLE positions DROP CONSTRAINT IF EXISTS positions_bounds_chk;
ALTER TABLE positions ADD CONSTRAINT positions_bounds_chk
    CHECK (horizon_h > 0 AND entry_price > 0
           AND signal_price > 0
           AND (stop_pct IS NULL OR stop_pct > 0)
           AND (stop_price IS NULL OR stop_price > 0)
           AND (exit_price IS NULL OR exit_price > 0)
           AND qty > 0 AND notional_usd > 0
           AND logic_version > 0);

DO $$
BEGIN
    -- 4. NULL ДОПУСТИМ ТОЛЬКО ПРИ logic_version >= 6, И ТОЛЬКО ОБА СРАЗУ
    --    (§4.2, §4.4 ТЗ). Половинчатое состояние — предел в процентах есть, а
    --    цены нет — не значит ничего: по нему нельзя ни проверить касание, ни
    --    сказать, что предела не было.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'positions_no_stop_chk') THEN
        ALTER TABLE positions
            ADD CONSTRAINT positions_no_stop_chk
            CHECK (
                CASE WHEN logic_version >= 6
                     THEN stop_pct IS NULL AND stop_price IS NULL
                     ELSE stop_pct IS NOT NULL AND stop_price IS NOT NULL
                END
            );
    END IF;

    -- 5. ИСХОД stop ДЛЯ ВЕРСИИ 6 НЕВОЗМОЖЕН (§4.4 ТЗ). Ограничение базы, а не
    --    проверка в коде: у версии 6 предела нет вовсе, и строка с таким
    --    исходом означала бы, что позиция закрыта уровнем, которого не
    --    существовало. Версии 5 ограничение не касается ни одной строкой.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'positions_v6_reason_chk') THEN
        ALTER TABLE positions
            ADD CONSTRAINT positions_v6_reason_chk
            CHECK (logic_version < 6 OR exit_reason IS NULL
                   OR exit_reason <> 'stop');
    END IF;

    -- 6. ИСХОД plus_exit ВОЗМОЖЕН ТОЛЬКО У ВЕРСИИ 6. Обратная сторона пункта
    --    5 и такое же проверяемое утверждение: правило версии 5 вторых суток
    --    не знает, и строка версии 5 с этим исходом означала бы, что кто-то
    --    пересчитал прежние позиции новым правилом — ровно то, что §1.2 ТЗ
    --    запрещает.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'positions_plus_exit_chk') THEN
        ALTER TABLE positions
            ADD CONSTRAINT positions_plus_exit_chk
            CHECK (exit_reason IS DISTINCT FROM 'plus_exit'
                   OR logic_version >= 6);
    END IF;

    -- 7. ФОРМА ЗАПИСИ ЗАКРЫТИЯ, ПО ОБРАЗЦУ МИГРАЦИИ 022 (§5.3 ТЗ). Момент и
    --    цена выхода обязательны у ВСЕХ исходов: пустая форма полей не должна
    --    читаться как измерение.
    --
    --    СЛУЖЕБНЫХ ИСХОДОВ, У КОТОРЫХ ЭТИХ ПОЛЕЙ НЕТ, В ЭТОЙ ТАБЛИЦЕ НЕ
    --    ЗАВЕДЕНО НИ ОДНОГО, и это стоит сказать прямо. В таблицах замеров
    --    (021, 022, 024) таким исходом был 'no_data' — признание того, что
    --    исход не измерен; здесь его роль играет 'data_gap', но у НЕГО момент
    --    и цена ЕСТЬ: позиция закрывается по последней известной цене, а то,
    --    что цена восстановлена, а не наблюдалась, помечается флагом
    --    outcome_certain = FALSE, а не пустотой. Поэтому исключений нет.
    --
    --    Общую форму («закрытая позиция обязана иметь итог») уже требует
    --    positions_shape_chk миграции 018; здесь то же требование записано от
    --    ИСХОДА, а не от статуса, и отдельным ограничением — чтобы отказ
    --    вставки называл именно то, чего не хватает.
    --
    --    ЧИСЛА БАРОВ ЗДЕСЬ НЕТ НАМЕРЕННО. §5.3 ТЗ требует момент и цену; барам
    --    же взяться неоткуда у строк, закрытых до появления этого поля, и
    --    потребовать их значило бы задним числом объявить прошлые строки
    --    неверными — при том что момент и цена у них есть.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'positions_exit_measured_chk') THEN
        ALTER TABLE positions
            ADD CONSTRAINT positions_exit_measured_chk
            CHECK (
                exit_reason IS NULL
                OR (closed_at IS NOT NULL AND exit_price IS NOT NULL)
            );
    END IF;
END $$;

COMMENT ON COLUMN positions.stop_pct IS
    'Предел убытка в процентах. NULL — ТОЛЬКО при logic_version >= 6 (Этап 9.2 '
    '§4.1): у версии 6 предела нет, и хранить вычисленный, но никогда не '
    'срабатывающий уровень запрещено — это данные, которые лгут.';
COMMENT ON COLUMN positions.stop_price IS
    'Цена предела убытка. NULL — ТОЛЬКО при logic_version >= 6 (Этап 9.2 §4.1). '
    'Для версии 5 поле обязательно, как и было.';
COMMENT ON CONSTRAINT positions_reason_chk ON positions IS
    'Закрытый перечень причин выхода. plus_exit (Этап 9.2 §5.1) — выход в '
    'ЧИСТЫЙ плюс после суток ожидания: цена выхода равна цене безубытка, '
    'поэтому итог такой сделки равен нулю по построению. Исход по сроку у '
    'версии 6 называется прежним именем timeout — событие то же, а срок '
    'записан в deadline_at.';
COMMENT ON CONSTRAINT positions_no_stop_chk ON positions IS
    'Этап 9.2 §4.2: пустой предел допустим ТОЛЬКО при logic_version >= 6. Для '
    'версии 5 stop_pct и stop_price остаются обязательными.';
COMMENT ON CONSTRAINT positions_v6_reason_chk ON positions IS
    'Этап 9.2 §4.4: у версии 6 предела нет, поэтому исход stop для неё '
    'физически невозможен — записано базой, а не обещанием кода.';

COMMIT;
