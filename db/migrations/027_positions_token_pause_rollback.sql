-- Откат миграции 027 (версия логики 7 §7).
--
-- ЧТО ВОССТАНАВЛИВАЕТСЯ: прежнее правило «один инструмент — одна ОТКРЫТАЯ
-- позиция» ДЛЯ ВСЕХ версий, то есть частичный уникальный индекс миграции 018
-- без оговорки о версии логики.
--
-- ДАННЫЕ ВЕРСИИ 7 ОТКАТ НЕ УДАЛЯЕТ (§10 ТЗ: «данные версии 7 при откате не
-- удаляются»). Он и не вправе: сделки состоялись, они измерены, и стирать их
-- ради возврата ограничения значило бы потерять ровно тот результат, ради
-- которого этап делался.
--
-- ОТКАТ ОТКАЗЫВАЕТСЯ РАБОТАТЬ, ЕСЛИ ПО КАКОМУ-ТО ТОКЕНУ СЕЙЧАС ОТКРЫТО БОЛЬШЕ
-- ОДНОЙ ПОЗИЦИИ, и это главное в этом файле. Восстановить прежний индекс при
-- таких строках можно ровно двумя способами: закрыть лишние позиции
-- выдуманной ценой или удалить их. Первое — данные, которые лгут; второе —
-- потеря факта. Ни того, ни другого откат не делает, а делать это МОЛЧА не
-- вправе тем более: он падает с внятным текстом и не меняет ни одной строки.
--
-- ЧТО ДЕЛАТЬ, ЕСЛИ ОТКАТ ОТКАЗАЛСЯ. Дождаться, пока лишние позиции версии 7
-- закроются сами (срок жизни — POSITION_MAX_HOLD_HOURS, 48 часов), и повторить.
-- Прежнее правило касается только ОТКРЫТЫХ позиций, поэтому закрытым строкам
-- версии 7 индекс не мешает ничем, сколько бы их ни было по одному токену.
-- Обходить проверку правкой этого файла нельзя: она и есть смысл файла.
--
-- ВАЖНО ПРО ПОРЯДОК ОТКАТА. Служба позиций при каждом старте приводит индекс к
-- виду версии 7 (``ensure_positions_schema``). Откат базы без отката образа
-- поэтому продержится до ближайшего перезапуска службы; §10 ТЗ и предполагает
-- откат целиком — .env, версию логики и миграцию вместе.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/027_positions_token_pause_rollback.sql

BEGIN;

DO $$
DECLARE
    busy_tokens BIGINT;
BEGIN
    SELECT count(*) INTO busy_tokens FROM (
        SELECT instrument_id
        FROM positions
        WHERE status = 'open'
        GROUP BY instrument_id
        HAVING count(*) > 1
    ) AS multi;
    IF busy_tokens > 0 THEN
        RAISE EXCEPTION
            'откат 027 невозможен: по % токенам сейчас открыто больше одной '
            'позиции. Прежний индекс такие строки не допускает, а закрыть их '
            'выдуманной ценой или удалить откат не вправе. Дождитесь закрытия '
            'по сроку (POSITION_MAX_HOLD_HOURS) и повторите',
            busy_tokens;
    END IF;
END $$;

DROP INDEX IF EXISTS ux_positions_one_open_per_instrument;

CREATE UNIQUE INDEX IF NOT EXISTS ux_positions_one_open_per_instrument
    ON positions (instrument_id) WHERE status = 'open';

COMMIT;
