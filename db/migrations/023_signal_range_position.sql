-- ЭТАП 9.1.5 §5. Положение цены сигнала в НЕДЕЛЬНОМ РАЗМАХЕ.
--
-- ЗАЧЕМ ЭТА ТАБЛИЦА. Владелец заметил настоящий пробел: система не различает
-- покупку у верхней границы недельного размаха и покупку у нижней, хотя это
-- разные сделки. Прежде чем строить по этому различию фильтр входа, надо
-- узнать, есть ли там вообще связь с исходом. Здесь лежит ФАКТ — где стояла
-- цена сигнала относительно уже случившихся семи суток, — и ничего больше.
--
-- ЭТО ЗАМЕР, А НЕ ВНЕДРЕНИЕ. Ни одно решение системы от таблицы не зависит:
-- LOGIC_VERSION остаётся 5, состав агентов, пороги и веса не трогаются,
-- сервисы decision, notify, evaluator, risk, barrier, trailing и positions о
-- ней не знают и знать не будут. РЕКОМЕНДАЦИЯ «ВНЕДРИТЬ ФИЛЬТР ПО ПОЛОЖЕНИЮ В
-- ДИАПАЗОНЕ» ЭТИМ ЭТАПОМ ЗАПРЕЩЕНА ПРЯМО (§1 ТЗ).
--
-- ЖЁСТКАЯ ГРАНИЦА ЭТАПА: signals НЕ ИЗМЕНЯЕТСЯ НИ ОДНОЙ КОЛОНКОЙ. Внешний ключ
-- смотрит ИЗ новой таблицы наружу, а не наоборот. ohlcv не трогается тоже:
-- содержимое таблицы производно от него и от signals целиком.
--
-- ON DELETE CASCADE стоит намеренно: строка здесь полностью восстановима
-- повторным прогоном scripts/range_position_9_1_5.py --apply. Осиротевшая
-- строка после удаления сигнала была бы числом ни о чём.
--
-- ПОЧЕМУ КЛЮЧ (signal_id, window_days), А НЕ ОДИН signal_id. Ширина окна —
-- параметр замера, а не свойство сигнала (§6 ТЗ: --window-days). Замер на семи
-- сутках и замер на трёх — два РАЗНЫХ наблюдения об одном сигнале, и класть их
-- в одну строку значило бы затирать одно другим при каждом прогоне.
--
-- ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ: ни исхода сигнала, ни доли достижения цели, ни
-- какой бы то ни было оценки. Исход уже посчитан Этапом 8.8 в
-- signal_outcomes_barrier, и второй его экземпляр однажды разошёлся бы с
-- первым. Здесь лежит ТОЛЬКО положение в размахе.
--
-- pos ВНЕ [0,1] — ШТАТНЫЙ СЛУЧАЙ, А НЕ ОШИБКА, и ограничением он не запрещён
-- намеренно (§5 ТЗ). Цена сигнала может оказаться выше недельного максимума
-- (пробитие вверх) или ниже минимума (пробитие вниз): окно кончается СТРОГО
-- ДО сигнала, поэтому сама цена сигнала в него не входит и обязана иметь право
-- выйти за его границы. Обрезание до [0,1] стёрло бы ровно ту группу, которая
-- может оказаться самой интересной.
--
-- Миграция идемпотентна. Откат — 023_signal_range_position_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/023_signal_range_position.sql

BEGIN;

CREATE TABLE IF NOT EXISTS signal_range_position (
    signal_id       BIGINT        NOT NULL REFERENCES signals(id) ON DELETE CASCADE,
    -- Ширина окна в сутках. Часть ключа: см. заголовок.
    window_days     SMALLINT      NOT NULL,
    -- Границы размаха: минимум low и максимум high по окну.
    range_low       NUMERIC(20,8) NOT NULL,
    range_high      NUMERIC(20,8) NOT NULL,
    -- Ширина размаха в процентах от нижней границы. Считается и хранится
    -- НАРАВНЕ с положением, а не «дополнительно»: в узком диапазоне разница
    -- между верхом и низом бывает меньше круговых издержек, и pos тогда не
    -- значит ничего. Без этой колонки такую строку нельзя отличить от
    -- содержательной.
    range_width_pct NUMERIC(12,6) NOT NULL,
    -- Положение цены сигнала в размахе: (цена − low) / (high − low).
    -- 0 — дно размаха, 1 — вершина. Вне [0,1] — пробитие, см. заголовок.
    pos             NUMERIC(10,6) NOT NULL,
    -- Момент ОТКРЫТИЯ последнего бара окна. Это и есть предъявляемое
    -- доказательство того, что в окно не попало будущее: расчёт обязан
    -- проверить last_bar_ts < signals.ts по КАЖДОЙ строке и остановиться, если
    -- это не так (§2.2 ТЗ). Колонка нужна затем, чтобы проверку можно было
    -- повторить запросом через месяц, а не верить журналу прогона.
    last_bar_ts     TIMESTAMPTZ   NOT NULL,
    -- Сколько баров реально попало в окно. Семь суток минутных баров — это
    -- 10 080 штук; меньшее число означает пропуски в ряде, и без этого числа
    -- полное окно неотличимо от дырявого.
    bars_in_window  INTEGER       NOT NULL,
    -- Чем считали. Значение сверено с кодом (src/barrier/outcomes.RESOLUTION_1M
    -- и RESOLUTION_1H), а не с текстом ТЗ; перечень тот же, что в миграциях
    -- 015, 016, 017 и 021, — второго словаря для одного и того же не заводится.
    resolution      TEXT          NOT NULL,
    computed_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT signal_range_position_pk PRIMARY KEY (signal_id, window_days)
);

-- Ограничения заводятся ОТДЕЛЬНО: CREATE TABLE IF NOT EXISTS существующую
-- таблицу не меняет, и на томе, где таблица уже создана прежним прогоном,
-- ограничения иначе не появились бы никогда.
DO $$
BEGIN
    -- Размах — это отрезок, а не точка: high строго больше low. Равенство
    -- означало бы деление на ноль в самой формуле pos, то есть неопределённое
    -- положение, записанное как определённое.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'signal_range_position_range_chk') THEN
        ALTER TABLE signal_range_position
            ADD CONSTRAINT signal_range_position_range_chk
            CHECK (range_high > range_low AND range_low > 0);
    END IF;

    -- Окно без единого бара — не окно. Ноль баров при заполненных границах
    -- означал бы, что границы взялись ниоткуда.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'signal_range_position_bars_chk') THEN
        ALTER TABLE signal_range_position
            ADD CONSTRAINT signal_range_position_bars_chk
            CHECK (bars_in_window > 0 AND window_days > 0);
    END IF;

    -- Ширина размаха положительна — она производна от range_high > range_low.
    -- Ограничение всё равно стоит: расхождение ширины с границами означало бы
    -- ошибку счёта, а не редкий рынок, и поймать её обязана база.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'signal_range_position_width_chk') THEN
        ALTER TABLE signal_range_position
            ADD CONSTRAINT signal_range_position_width_chk
            CHECK (range_width_pct > 0);
    END IF;

    -- ПЕРЕЧЕНЬ РАЗРЕШЕНИЙ ЗАКРЫТ и совпадает с миграциями 015/016/017/021.
    -- Замер §2.1 ТЗ считается по МИНУТНЫМ барам, поэтому фактически пишется
    -- только '1m'; '1h' оставлено в перечне затем, чтобы словарь значений был
    -- один на весь проект, а не свой в каждой таблице.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conname = 'signal_range_position_resolution_chk') THEN
        ALTER TABLE signal_range_position
            ADD CONSTRAINT signal_range_position_resolution_chk
            CHECK (resolution IN ('1m', '1h'));
    END IF;
END $$;

-- Выборки §4 ТЗ идут по ширине окна и по положению, а не по signal_id: главная
-- таблица этапа — «успех по корзинам pos», и она читает всю ширину окна разом.
CREATE INDEX IF NOT EXISTS ix_signal_range_position_window
    ON signal_range_position (window_days, pos);

-- Право на чтение — той же роли, что и у остальных таблиц замеров, если она
-- заведена. Отсутствие роли не ошибка: на части машин её нет.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'agenttrade_ro') THEN
        GRANT SELECT ON signal_range_position TO agenttrade_ro;
    END IF;
END $$;

COMMENT ON TABLE signal_range_position IS
    'Этап 9.1.5: положение цены сигнала в недельном размахе и ширина этого '
    'размаха. ЗАМЕР, а не внедрение: LOGIC_VERSION остаётся 5, ни одно '
    'решение системы от этой таблицы не зависит, фильтр входа по положению в '
    'диапазоне этим этапом ЗАПРЕЩЁН.';

COMMIT;
