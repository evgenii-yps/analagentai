-- ВЕРСИЯ ЛОГИКИ 7 §7. Снятие правила «один инструмент — одна позиция» ТОЛЬКО
-- ДЛЯ ВЕРСИИ 7.
--
-- ЧТО ИМЕННО ЗДЕСЬ ПРОИСХОДИТ И ПОЧЕМУ МИГРАЦИЯ ВООБЩЕ НУЖНА. Исполнитель
-- проверил схему, как требует §7.2 ТЗ: правило «один инструмент — одна
-- позиция» закреплено НЕ ТОЛЬКО кодом. Его записывает частичный уникальный
-- индекс ``ux_positions_one_open_per_instrument`` (миграция 018) — и записан он
-- там намеренно: «проверка в коде переживает ровно до первой гонки». Снять
-- правило одним лишь кодом поэтому нельзя: вторая позиция по токену получила
-- бы отказ вставки, сервис счёл бы его штатной гонкой
-- (``positions_race_skipped=1``), и сделок не прибавилось бы НИ ОДНОЙ — при
-- совершенно честном виде журнала.
--
-- ОСЛАБЛЕНИЕ КАСАЕТСЯ ТОЛЬКО ВЕРСИИ 7 (§7.1, §7.2 ТЗ) — тем же приёмом, каким
-- миграция 025 ослабила NOT NULL только для версии 6. Условие индекса дополнено
-- ``logic_version < 7``: строки версий 5 и 6 остаются под тем же запретом, под
-- которым открывались, и две одновременные позиции по одному токену у них
-- по-прежнему невозможны. Ни одной строки эта миграция НЕ ИЗМЕНЯЕТ: ни UPDATE,
-- ни DELETE здесь нет вовсе. Итог версии 5 (−$0.68088 на 88 сделках) обязан
-- остаться прежним до цента, и проверяется это до и после применения (§9 ТЗ).
--
-- ЧЕГО ЗДЕСЬ НЕТ. Индекс ``ux_positions_signal`` («один сигнал — не больше
-- одной позиции») НЕ ТРОГАЕТСЯ. Он не про частоту сделок, а про повторное
-- чтение одного и того же сигнала после перезапуска: две позиции по ОДНОМУ
-- сигналу — это не две сделки, а одна, записанная дважды.
--
-- НОВЫХ КОЛОНОК И ТАБЛИЦ ЭТАП НЕ ЗАВОДИТ. Пауза по токену (§4 ТЗ) — правило
-- КОДА над уже имеющейся колонкой ``opened_at``; хранить для неё отдельную
-- отметку значило бы завести второй источник истины о том же факте.
--
-- ПОЧЕМУ ИНДЕКС ПЕРЕСОЗДАЁТСЯ, А НЕ «ДОПОЛНЯЕТСЯ». Условие частичного индекса
-- в PostgreSQL не меняется на месте: единственный способ — снять и поставить
-- заново (тот же приём, что у CHECK в миграциях 019 и 025). Имя сохраняется
-- прежним намеренно: индекс описывает ТО ЖЕ правило, просто с оговоркой о
-- версии, и второе имя для одного правила заставило бы каждую будущую проверку
-- схемы знать оба.
--
-- Миграция идемпотентна: повторный прогон видит индекс уже с ``logic_version``
-- в определении и не делает ничего. Откат — 027_positions_token_pause_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/027_positions_token_pause.sql

BEGIN;

DO $$
BEGIN
    -- Снимается индекс СО СТАРЫМ ОПРЕДЕЛЕНИЕМ, а не по имени: имя после этой
    -- миграции то же самое, и безусловный DROP/CREATE на каждом прогоне
    -- оставлял бы таблицу на доли секунды вовсе без правила.
    IF EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE indexname = 'ux_positions_one_open_per_instrument'
          AND indexdef NOT LIKE '%logic_version%'
    ) THEN
        DROP INDEX ux_positions_one_open_per_instrument;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_positions_one_open_per_instrument
    ON positions (instrument_id)
    WHERE status = 'open' AND logic_version < 7;

COMMENT ON INDEX ux_positions_one_open_per_instrument IS
    'Правило «один инструмент — одна ОТКРЫТАЯ позиция» — ТОЛЬКО до версии 7. '
    'С версии 7 (ТЗ 7 §3 A2) по одному токену допускается произвольное число '
    'одновременно открытых позиций, а поток ограничивает пауза по токену '
    'POSITION_TOKEN_PAUSE_MIN. Строки версий 5 и 6 остаются под прежним '
    'запретом: их правила не переписываются задним числом.';

COMMIT;
