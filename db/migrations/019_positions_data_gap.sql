-- ЭТАП 9.1.1 §6. Пятая причина выхода: data_gap («пробел в данных»).
--
-- ЗАЧЕМ. До этой миграции позиция, по инструменту которой прервался ряд свечей,
-- оставалась открытой НАВСЕГДА и занимала слот навсегда. Правило выхода
-- (src/positions/rules.check_exit) возвращает «исхода нет» в двух случаях: бар
-- срока не предъявлен — неизвестно, кончилось окно или данные ещё не подъехали;
-- и бар срока есть, а баров окна до срока нет вовсе. Оба поведения правильные:
-- правило не выдумывает цену, которой не было. Но выхода из этого состояния не
-- существовало ни одного.
--
-- Решение владельца от 30.08.2026: по истечении срока плюс запас
-- (POSITION_GAP_GRACE_SEC, по умолчанию 2 часа) позиция закрывается по
-- ПОСЛЕДНЕЙ ИЗВЕСТНОЙ цене и помечается причиной data_gap.
--
-- ЭТО НЕ ИСХОД РЫНКА, А ПРИЗНАНИЕ ТОГО, ЧТО ИСХОД НЕ ИЗМЕРЕН. Поэтому у таких
-- строк outcome_certain = FALSE всегда, и в средние и суммы по прибыльности
-- они НЕ ВХОДЯТ (см. src/bot/queries.positions_summary): выдуманная цена не
-- должна попадать в результат системы наравне с измеренными. Считать их всё же
-- надо — отдельной строкой: пять позиций, закрытых по пробелу, означают, что
-- сбор данных встал, и знать об этом нужно.
--
-- ПОЧЕМУ ОГРАНИЧЕНИЕ ПЕРЕСОЗДАЁТСЯ ЦЕЛИКОМ, а не «дополняется». В PostgreSQL
-- CHECK нельзя расширить на месте: единственный способ — снять и поставить
-- заново. DROP ... IF EXISTS + ADD делает миграцию идемпотентной и безопасной
-- на базе, где 018 уже применена, и на базе, где её ещё нет.
--
-- Миграция идемпотентна. Откат — 019_positions_data_gap_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/019_positions_data_gap.sql

BEGIN;

ALTER TABLE positions DROP CONSTRAINT IF EXISTS positions_reason_chk;

ALTER TABLE positions ADD CONSTRAINT positions_reason_chk
    CHECK (exit_reason IS NULL OR exit_reason IN
           ('target', 'stop', 'timeout', 'ambiguous', 'data_gap'));

COMMENT ON CONSTRAINT positions_reason_chk ON positions IS
    'Закрытый перечень причин выхода (Этап 9.1.1 §6). data_gap — не исход '
    'рынка, а признание того, что исход не измерен: ряд свечей прервался, срок '
    'истёк, позиция закрыта по последней известной цене. В средние и суммы по '
    'прибыльности такие строки не входят.';

COMMIT;
