-- Откат миграции 028 (этап 9.3 §7.1).
--
-- ЧТО УДАЛЯЕТСЯ: таблица журнала отказов во входе целиком, вместе со строками.
--
-- ЭТО ЕДИНСТВЕННЫЙ ОТКАТ ЭТАПА, КОТОРЫЙ ТЕРЯЕТ ДАННЫЕ, и потерю эту он вправе
-- допустить ровно потому, что теряет: отказы — не сделки. Сделка, которой не
-- случилось, не влияет ни на один итог версии 7; её запись нужна, чтобы
-- ответить на вопрос «почему сделок столько», и вопрос этот задаётся живой
-- системе, а не архиву. Таблицу ``positions`` откат не трогает ВОВСЕ — ни
-- одной строки, ни одного столбца.
--
-- ПЕРЕД УДАЛЕНИЕМ СТОИТ СНЯТЬ ИТОГ, если он ещё нужен:
--   SELECT logic_version, reason, count(*)
--     FROM public.position_rejections GROUP BY 1, 2 ORDER BY 1, 3 DESC;
-- Откат этого не делает за владельца: молча сохранить итог «на всякий случай»
-- значило бы оставить в базе вторую таблицу, о которой никто не помнит.
--
-- Ручное применение (каталог миграций в контейнер НЕ смонтирован — см. ниже):
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       -v ON_ERROR_STOP=1 -f - < db/migrations/028_position_rejections_rollback.sql
--
-- ПОЧЕМУ ИМЕННО ТАК, А НЕ ЧЕРЕЗ ПУТЬ ВНУТРИ КОНТЕЙНЕРА. Первая редакция этой
-- шапки предписывала `-f /docker-entrypoint-initdb.d/migrations/…`, и команда
-- падала: в ``docker-compose.yml`` смонтирован ОДИН файл
-- (``./db/init.sql:/docker-entrypoint-initdb.d/init.sql:ro``), а каталога
-- ``migrations`` внутри контейнера нет вовсе. Файл поэтому подаётся на
-- стандартный ввод с хоста.
--
-- ``-v ON_ERROR_STOP=1`` ОБЯЗАТЕЛЕН. Без него psql, встретив ошибку,
-- продолжает выполнять остальные команды файла и завершается с кодом 0 —
-- миграция выглядит применённой, а применена наполовину.

