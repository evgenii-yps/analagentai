-- ЭТАП 9.1.2 §7. Две отметки о записи позиции в торговый журнал Google Таблиц.
--
-- ЗАЧЕМ ДВЕ, А НЕ ОДНА. Строка в листе создаётся ДВАЖДЫ по времени: при
-- ОТКРЫТИИ позиции пишутся столбцы A–G (сделка видна сразу, пока она ещё идёт),
-- при ЗАКРЫТИИ в ТУ ЖЕ строку дозаписываются H, I, J. Это два разных события с
-- разным исходом: запись открытия могла пройти, а запись закрытия — нет. Одна
-- отметка не смогла бы различить «строка создана» и «строка достроена», и после
-- сбоя сети между ними выгрузка либо потеряла бы закрытие, либо создала бы
-- вторую строку той же сделки.
--
-- ОТМЕТКА СТАВИТСЯ ТОЛЬКО ПОСЛЕ ok:true ПО СВОЕЙ ОПЕРАЦИИ, всей пачке одним
-- UPDATE ... WHERE id = ANY($1). При любой ошибке отправки отметка не ставится,
-- и пачка повторяется в следующий раз. Повторная запись одной позиции
-- невозможна по построению.
--
-- ПОЧЕМУ ПРИЗНАК ЛЕЖИТ В БАЗЕ, А НЕ В ПАМЯТИ ПРОЦЕССА. Выгрузка запускается
-- одноразовым контейнером из cron каждые 15 минут: памяти между запусками у неё
-- нет вовсе.
--
-- Миграция идемпотентна. Откат — 020_positions_sheet_export_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/020_positions_sheet_export.sql

BEGIN;

ALTER TABLE positions ADD COLUMN IF NOT EXISTS sheet_opened_at TIMESTAMPTZ;
ALTER TABLE positions ADD COLUMN IF NOT EXISTS sheet_closed_at TIMESTAMPTZ;

COMMENT ON COLUMN positions.sheet_opened_at IS
    'Момент подтверждённой записи СТРОКИ ОТКРЫТИЯ (столбцы A–G) в торговый '
    'журнал Google Таблиц (Этап 9.1.2). NULL — строки в листе ещё нет.';
COMMENT ON COLUMN positions.sheet_closed_at IS
    'Момент подтверждённой ДОЗАПИСИ закрытия (столбцы H, I, J) в ту же строку '
    '(Этап 9.1.2). NULL — строка есть, но выход в неё ещё не дописан.';

-- ЧАСТИЧНЫЙ ИНДЕКС ПО ОЧЕРЕДИ НА ЗАПИСЬ. Условие повторяет обе выборки
-- выгрузки: «строки ещё нет» ИЛИ «позиция закрыта, а выход не дописан». Индекс
-- по всей таблице был бы во много раз больше и отвечал бы на другой вопрос —
-- очередь составляет малую часть строк и быстро пустеет.
CREATE INDEX IF NOT EXISTS positions_sheet_pending_idx
    ON positions (opened_at)
    WHERE sheet_opened_at IS NULL OR (status = 'closed' AND sheet_closed_at IS NULL);

COMMIT;
