-- ЭТАП 9.1.1 §7.6. Признак «строка позиции уже записана в Google Таблицу».
--
-- ЗАЧЕМ ЭТА КОЛОНКА. Лист «торговля тест апи окх чтение» моделирует ОДИН
-- кошелёк с реинвестированием: объём каждой строки равен объёму предыдущей
-- плюс прибыль предыдущей (замер по заполненному образцу из 16 строк:
-- 10,00000 + 0,01995 = 10,01995; 10,01995 + 0,01531 = 10,03526). Вторая строка
-- той же сделки удвоила бы её прибыль во ВСЕЙ последующей цепочке, и числа при
-- этом остались бы правдоподобными — а это худший вид ошибки.
--
-- ПРИЗНАК «УЖЕ ЗАПИСАНО» ОБЯЗАН ЛЕЖАТЬ В БАЗЕ, А НЕ В ПАМЯТИ ПРОЦЕССА.
-- Перезапуск сервиса после сбоя сети — штатное событие, и признак, живущий в
-- памяти, его не переживает.
--
-- МИГРАЦИЯ 018 УЖЕ ПРИМЕНЕНА НА СЕРВЕРЕ и не редактируется: колонка идёт
-- отдельным файлом. Правка применённой миграции означала бы, что на разных
-- машинах под одним номером лежат разные описания схемы.
--
-- ПОРЯДОК ДЕЙСТВИЙ В КОДЕ ЖЁСТКИЙ: сначала позиция закрывается в базе, потом
-- пишется строка в лист, и только после ПОДТВЕРЖДЁННОЙ записи ставится эта
-- отметка. Обратный порядок при сбое между шагами дал бы строку в листе без
-- позиции в базе — число, которое нечем проверить.
--
-- Миграция идемпотентна. Откат — 019_positions_sheet_export_rollback.sql.
--
-- Ручное применение:
--   docker compose exec -T postgres psql -U agenttrade -d agenttrade \
--       < db/migrations/019_positions_sheet_export.sql

BEGIN;

ALTER TABLE positions ADD COLUMN IF NOT EXISTS sheet_exported_at TIMESTAMPTZ;

COMMENT ON COLUMN positions.sheet_exported_at IS
    'Момент ПОДТВЕРЖДЁННОЙ записи строки позиции в Google Таблицу (Этап 9.1.1 '
    '§7.6). NULL — не записана. Непустое значение означает «в лист уже ушла» и '
    'вторую строку той же сделки не допускает ни после перезапуска, ни после '
    'повторного прогона.';

-- Частичный индекс по ОЧЕРЕДИ НА ЗАПИСЬ. Отбор идёт по «закрыта и ещё не
-- записана», и это малая часть таблицы: индекс по всей колонке был бы вчетверо
-- больше и отвечал бы на другой вопрос.
CREATE INDEX IF NOT EXISTS ix_positions_sheet_pending
    ON positions (closed_at ASC)
    WHERE status = 'closed' AND sheet_exported_at IS NULL;

COMMIT;
