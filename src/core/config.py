    EVAL_HORIZONS: str = "1,4,12,24"
    # Главный горизонт: по нему пишется сводка в signals и сигнал закрывается.
    EVAL_PRIMARY_HORIZON: str = "4"
    # Прежний формат («1h,4h», «4h») читается тоже: значение из .env не обязано
