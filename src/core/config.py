    @field_validator("NOTIFY_DAILY_SUMMARY_UTC")
    @classmethod
    def _daily_summary_time_is_utc_hh_mm(cls, value: str) -> str:
        """Время суточной сводки — ``ЧЧ:ММ`` по UTC, и разбирается ЗДЕСЬ (§6.2).

        Разбор в момент чтения настроек, а не в момент отправки, выбран
        намеренно: опечатка в ``.env`` обязана уронить сервис при старте, а не
        обнаружиться тем, что сводка не пришла ни разу и никто этого не
        заметил — сводка выходит раз в сутки, и «не пришла» неотличимо от «ещё
        не время».
        """
        text = str(value).strip()
        parts = text.split(":")
        if len(parts) != 2 or not all(part.isdigit() for part in parts):
            raise ValueError(
                f"NOTIFY_DAILY_SUMMARY_UTC={value!r} не похоже на время UTC: "
                "ожидается ЧЧ:ММ, например 06:00"
            )
        hour, minute = int(parts[0]), int(parts[1])
        if not (0 <= hour <= 23 and 0 <= minute <= 59):
            raise ValueError(
                f"NOTIFY_DAILY_SUMMARY_UTC={value!r} вне суток: часы 0–23, "
                "минуты 0–59"
            )
        return f"{hour:02d}:{minute:02d}"

