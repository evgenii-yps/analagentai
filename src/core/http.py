from __future__ import annotations

# Браузерная подпись. Конкретная версия значения не имеет — важно, что подпись
# не питоновская; менять её при обновлении браузеров не требуется и не нужно.
EXCHANGE_USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36"
)

# Заголовки, которые браузер шлёт вместе с подписью. Без них запрос выглядит
# как «браузер, который не принимает ответов», и защита биржи вправе счесть это
# подозрительным. Набор намеренно короткий: всё лишнее — это лишнее, что может
# однажды сломаться.
_ACCEPT = "application/json, text/plain, */*"
_ACCEPT_LANGUAGE = "en-US,en;q=0.9"


def exchange_headers(extra: dict[str, str] | None = None) -> dict[str, str]:
    """Заголовки для ЛЮБОГО запроса к бирже по HTTP.

    ``extra`` добавляется поверх и может перекрыть значения — это нужно
    эндпоинтам, требующим своих заголовков (ключ, подпись, срок). Подпись
    клиента перекрывать не следует: ради неё модуль и существует.
    """
    headers = {
        "User-Agent": EXCHANGE_USER_AGENT,
        "Accept": _ACCEPT,
        "Accept-Language": _ACCEPT_LANGUAGE,
    }
    if extra:
        headers.update(extra)
    return headers


def is_browser_user_agent(value: str | None) -> bool:
    """Похожа ли подпись на браузерную. Нужна проверкам, а не запросам.

    Правило намеренно грубое: подпись, начинающаяся с ``Mozilla/``, проходит,
    всё остальное — нет. Точнее проверять нечего: биржа не публикует список
    допустимых подписей, и любая «умная» проверка была бы догадкой о её
    внутренностях.
    """
    return bool(value) and str(value).startswith("Mozilla/")
