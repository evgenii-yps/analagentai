"""Тексты сообщений об открытии и закрытии СДЕЛКИ (§6.2 ТЗ 9.3).

Модуль ЧИСТЫЙ: данные → строка. Отправка — существующей функцией
``src.notify.telegram.send_message``.

СЛОВО «ВИРТУАЛЬНО» В ЗАГОЛОВКЕ ОБЯЗАТЕЛЬНО и убираться не должно, пока позиции
виртуальные. §6.2 ТЗ 9.3 выписывает образцы сообщений без него, и это
единственное место, где исполнитель от образца отступил — сознательно и в одну
сторону: строка «🟢 Открыта сделка #41 · BTC/USDT · вход $77 602.70» без этой
пометки читается как отчёт о НАСТОЯЩЕЙ сделке. Человек, читающий поток, не
обязан помнить, какой этап проекта сейчас идёт; ошибиться тут можно только в
одну сторону, и цена ошибки — не опечатка, а неверное представление о том,
рискуют ли настоящие деньги. Всё остальное в образцах воспроизведено построчно.

ТРИ СООБЩЕНИЯ, И БОЛЬШЕ НИКАКИХ (§6.2): открытие, закрытие и суточная сводка
(``src.notify.daily_trades``). Сообщения о сигналах прекращены флагом
``NOTIFY_SIGNALS_ENABLED=false`` (§6.1).

ПРЕДОХРАНИТЕЛЬ НА ПОТОК ЖИВЁТ НЕ ЗДЕСЬ, А В ОТПРАВКЕ (``runner._send``,
``NOTIFY_TRADES_MAX_PER_HOUR``, §6.3): текст сообщения не должен зависеть от
того, сколько сообщений ушло до него.
"""

from __future__ import annotations

import html
from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

# Часовой пояс отображения (заказчик в МСК). Сервер и БД живут в UTC.
_MSK = ZoneInfo("Europe/Moscow")

# Русские названия причин выхода. Ключи — те же машиночитаемые значения, что
# лежат в колонке exit_reason; человеку показывается перевод, запросу — ключ.
EXIT_RU = {
    "target": "цель достигнута",
    "stop": "сработал предел убытка",
    "timeout": "истёк срок",
    "ambiguous": "цель и предел в одной свече — итог по пределу",
    # §6.2 ТЗ 9.3 называет этот исход «пропали данные» — короче и точнее для
    # строки «Причина:», где перечень образца закрыт четырьмя формулировками.
    "data_gap": "пропали данные",
    # Этап 9.2 §8.1: новый исход назван человеческим языком, а не ключом.
    # «plus_exit» в сообщении означало бы, что человек обязан помнить перечень
    # машиночитаемых значений колонки.
    "plus_exit": "вышли в плюс после суток",
}

# ИСХОД ПО СРОКУ У ВЕРСИИ 6 НАЗЫВАЕТСЯ ТЕМ ЖЕ КЛЮЧОМ 'timeout', НО СРОК У НЕГО
# ДРУГОЙ (§5.2, §8.1 ТЗ 9.2), и в сообщении это обязано быть видно: «истёк
# срок» после сорока восьми часов ожидания и «истёк срок» после суток — разные
# события для того, кто читает поток. Число берётся из строки позиции, а не из
# настройки: срок записан в ней при входе.
EXIT_RU_WITH_HOURS = {"timeout": "истёк срок {hours} ч"}


def exit_ru(exit_reason: str, hold_hours: int | None = None) -> str:
    """Причина выхода человеческим языком; при известном сроке — со сроком.

    ``hold_hours=None`` — срок неизвестен вызывающему; тогда печатается общая
    формулировка. Выдумывать срок нельзя: «истёк срок 24 ч» у позиции, жившей
    сорок восемь, — это неверное утверждение, а не приблизительное.
    """
    if hold_hours is not None and exit_reason in EXIT_RU_WITH_HOURS:
        return EXIT_RU_WITH_HOURS[exit_reason].format(hours=int(hold_hours))
    return EXIT_RU.get(exit_reason, exit_reason)


def _esc(text: Any) -> str:
    """Экранирование под parse_mode=HTML."""
    return html.escape(str(text))


def _price(value: float) -> str:
    """Цена с разделителем тысяч. Знаков — по величине: у DOGE их нужно больше.

    Пять знаков после запятой у копеечных инструментов и два у дорогих — не
    украшение: 0.21 вместо 0.21437 у DOGE прячет ровно тот масштаб движения, в
    котором эта позиция и живёт.
    """
    value = float(value)
    digits = 2 if abs(value) >= 100 else (4 if abs(value) >= 1 else 6)
    return f"{value:,.{digits}f}".replace(",", " ")


def _msk(ts: datetime) -> str:
    """UTC → ``dd.mm HH:MM MSK``."""
    return ts.astimezone(_MSK).strftime("%d.%m %H:%M") + " MSK"


def bars_ru(count: int) -> str:
    """Число баров по-русски: ``1 бар``, ``3 бара``, ``11 баров``.

    Склонение здесь не украшение: «увидели 3 баров» читается как опечатка, а
    сообщение, выглядящее опечаткой, читают невнимательно.
    """
    count = int(count)
    tail = abs(count) % 100
    last = abs(count) % 10
    if 11 <= tail <= 14 or last == 0 or last >= 5:
        word = "баров"
    elif last == 1:
        word = "бар"
    else:
        word = "бара"
    return f"{count} {word}"


def hhmm(seconds: float) -> str:
    """Длительность в формате ``ЧЧ:ММ`` (§6.2 ТЗ 9.3).

    ЧАСЫ НЕ ПЕРЕПОЛНЯЮТСЯ В СУТКИ: сделка живёт до 48 часов, и «47:12» — это
    сорок семь часов, а не «1 день 23 часа». Пересчёт в дни заставил бы
    читателя сверять срок сделки с настройкой в уме.
    """
    total = max(0, int(seconds))
    return f"{total // 3600:02d}:{(total % 3600) // 60:02d}"


def held_ru(seconds: float) -> str:
    """Длительность удержания словами: ``3 ч 41 мин``, ``17 мин``."""
    total = max(0, int(seconds))
    hours, minutes = divmod(total // 60, 60)
    if hours:
        return f"{hours} ч {minutes} мин"
    return f"{minutes} мин"


def opened_text(
    *,
    position_id: int,
    symbol: str,
    entry_price: float,
    target_price: float,
    target_pct: float,
    probability: float | None,
    logic_version: int,
    stop_pct: float | None,
    hold_hours: int,
) -> str:
    """Сообщение об открытии сделки — образец §6.2 ТЗ 9.3, сообщение 1.

    НОМЕР СДЕЛКИ В ПЕРВОЙ СТРОКЕ — не украшение. По одному токену теперь бывает
    несколько одновременных сделок (§4.2 ТЗ), и без номера два сообщения об
    открытии BTC/USDT подряд неотличимы от одного, присланного дважды. По этому
    же номеру сделка находится в торговом журнале и в ``/positions``.

    ``stop_pct is None`` И ЕСТЬ ПРИЗНАК ПРАВИЛА БЕЗ ПРЕДЕЛА УБЫТКА, и приходит
    он из строки позиции, а не из настройки: сообщение не обязано знать, какая
    версия сейчас в ``.env``. Написать о пределе у позиции, у которой его нет,
    значило бы ввести в заблуждение.
    """
    prob = "—" if probability is None else f"{float(probability):.2f}"
    limit = (
        "без предела убытка" if stop_pct is None
        else f"предел убытка −{float(stop_pct):.2f}%"
    )
    return (
        f"🟢 <b>Открыта сделка #{int(position_id)}</b> (виртуально)\n"
        f"{_esc(symbol)} · вход ${_price(entry_price)}\n"
        f"Цель ${_price(target_price)} (+{float(target_pct):.2f}%) · "
        f"вероятность {prob}\n"
        f"Правило v{int(logic_version)} · {limit} · срок {int(hold_hours)} ч"
    )


def closed_text(
    *,
    position_id: int,
    symbol: str,
    exit_reason: str,
    entry_price: float,
    exit_price: float,
    net_pnl_pct: float,
    net_pnl_usd: float,
    cost_pct: float,
    held_sec: float,
    hold_hours: int | None = None,
) -> str:
    """Сообщение о закрытии сделки — образец §6.2 ТЗ 9.3, сообщение 2.

    ИЗДЕРЖКИ НАЗВАНЫ ЧИСЛОМ НАМЕРЕННО: итог показан УЖЕ за их вычетом, и без
    этой строки человек, сверяющий числа с ценами входа и выхода, каждый раз
    обнаруживал бы недостачу и искал ошибку.

    ``hold_hours`` — срок ЭТОЙ сделки; при исходе ``timeout`` он попадает в
    текст («истёк срок 48 ч»). Срок берётся из строки позиции, а не из
    настройки: «истёк срок 48 ч» у сделки, жившей сутки, — это неверное
    утверждение, а не приблизительное.

    ВРЕМЯ В СДЕЛКЕ — В ФОРМАТЕ ``ЧЧ:ММ`` (§6.2), а не «3 ч 41 мин». Сделки
    живут до 48 часов, и «41 ч 12 мин» рядом с «03:41» в суточной сводке
    заставляли бы читателя каждый раз переводить одно в другое.
    """
    return (
        f"🔴 <b>Закрыта сделка #{int(position_id)}</b> (виртуально)\n"
        f"{_esc(symbol)} · вход ${_price(entry_price)} → "
        f"выход ${_price(exit_price)}\n"
        f"Итог {float(net_pnl_pct):+.2f}% (${float(net_pnl_usd):+.3f}) "
        f"с учётом издержек {float(cost_pct):.2f}%\n"
        f"Причина: {_esc(exit_ru(exit_reason, hold_hours))}\n"
        f"Время в сделке {hhmm(held_sec)}"
    )


def data_gap_text(
    *,
    position_id: int,
    symbol: str,
    entry_price: float,
    exit_price: float,
    last_bar_ts: datetime,
    gap_sec: float,
    net_pnl_pct: float,
    net_pnl_usd: float,
    cost_pct: float,
    held_sec: float,
    bars_held: int,
) -> str:
    """Закрытие ПО ПРОБЕЛУ В ДАННЫХ — то же сообщение 2, плюс оговорка.

    ФОРМА ВЗЯТА ИЗ §6.2 ТЗ 9.3, И ЭТО ИЗМЕНЕНИЕ ПРОТИВ ЭТАПА 9.1.1, где у
    пробела был отдельный текст с другим заголовком. Основание — сам §6.2:
    «пропали данные» перечислено там среди значений строки «Причина:»
    сообщения 2, то есть архитектор ждёт одного сообщения о закрытии на все
    исходы. Довод этапа 9.1.1 при этом не отброшен, а перенесён в оговорку:
    результата здесь нет — есть последняя известная цена и признание того, что
    исход измерить не удалось, и человек обязан увидеть это в самом сообщении,
    а не вычислить из мелкого примечания.

    ЧИСЛА НАЗВАНЫ СВОИМИ ИМЕНАМИ: сколько времени не было данных, от какого
    момента взята цена и что итог в статистику не идёт.
    """
    # ДВА РАЗНЫХ СЛУЧАЯ, И ПУТАТЬ ИХ НЕЛЬЗЯ. Если хоть один бар видели, цена
    # выхода — настоящая цена из прошлого, и назвать её момент обязательно.
    # Если не видели ни одного, никакой «последней известной цены» не было
    # вовсе: выход посчитан по цене ВХОДА, и написать «по последней известной
    # цене от такого-то времени» значило бы сослаться на наблюдение, которого
    # не существует.
    if int(bars_held) > 0:
        seen_line = (
            f"Цена выхода — последняя известная, от {_msk(last_bar_ts)}; "
            f"успели увидеть {bars_ru(bars_held)} движения"
        )
    else:
        seen_line = (
            "Ни одной свечи после входа не пришло: выход посчитан по цене "
            "входа, движения не наблюдали вовсе — оценить сделку нечем"
        )
    return (
        closed_text(
            position_id=position_id,
            symbol=symbol,
            exit_reason="data_gap",
            entry_price=entry_price,
            exit_price=exit_price,
            net_pnl_pct=net_pnl_pct,
            net_pnl_usd=net_pnl_usd,
            cost_pct=cost_pct,
            held_sec=held_sec,
        )
        + f"\n⚠ Данных по инструменту не было {held_ru(gap_sec)}. Итог "
          "В СТАТИСТИКУ НЕ ИДЁТ: цена выхода не наблюдалась, а восстановлена\n"
        + seen_line
    )
