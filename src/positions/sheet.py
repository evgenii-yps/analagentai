"""Сборка строки закрытой позиции для Google Таблицы (Этап 9.1.1 §7). ЧИСТЫЙ модуль.

Ни сети, ни базы, ни времени «сейчас»: данные → объект строки. Отправка живёт в
``src.export.sheets.post_position_row``, приёмник — в ``deploy/apps_script.gs``.

ЗАПИСЬ ВЕДЁТСЯ РОВНО В ВОСЕМЬ СТОЛБЦОВ: A, B, C, D, F, H, I, J. Столбец G
(«вход - объем») и столбцы K..S — ФОРМУЛЫ ЛИСТА, и запись значения в такой
столбец заменила бы формулу числом: лист перестал бы пересчитываться, а
выглядел бы работающим. Поэтому набор столбцов задан здесь константой и
собираемый объект содержит РОВНО ЕЁ — лишний ключ в нём попросту неоткуда
взять.

ПОЧЕМУ В ЛИСТ ИДЁТ ТОЛЬКО ОДИН ИНСТРУМЕНТ. Замер по заполненному образцу
(16 строк): G первой строки задан вручную ($10,00000), дальше G каждой строки =
G предыдущей + прибыль предыдущей (10,00000 + 0,01995 = 10,01995;
10,01995 + 0,01531 = 10,03526). То есть лист моделирует ОДИН кошелёк с
реинвестированием, а система ведёт ПЯТЬ независимых слотов без него. Строки
пяти слотов, идущие вперемешку, сложились бы в одну цепочку, и лист показал бы
доходность несуществующего счёта — числа при этом получились бы правдоподобные,
а это худший вид ошибки.

ЧАСОВОЙ ПОЯС ВСЕХ ЧЕТЫРЁХ ПОЛЕЙ ВРЕМЕНИ — NOTIFY_TIMEZONE (Europe/Moscow), тот
же, что в сообщениях Telegram: человек, сверяющий лист с сообщением бота, обязан
видеть одно и то же время. Столбца с поясом в листе нет, поэтому пояс
принимается параметром и называется в отчёте прямым текстом.

В СТОЛБЦЕ B СТОИТ ВРЕМЯ СИГНАЛА, В A — ДАТА ВХОДА. Это РАЗНЫЕ моменты (между
ними entry_lag_sec, на боевом сервере 25 секунд), и заголовки листа названы
именно так. Подменять одно другим нельзя.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

# Столбцы, в которые пишет система. Перечень ЗАКРЫТ: остальные столбцы листа —
# формулы владельца, и трогать их нельзя ни одним значением.
SHEET_COLUMNS: tuple[str, ...] = ("A", "B", "C", "D", "F", "H", "I", "J")

# Ожидаемые заголовки строки 1 в этих столбцах. Владелец правит лист руками, и
# молчаливая запись в переименованные столбцы — это порча данных: приёмник
# сверяет строку 1 с этим перечнем и при расхождении ОТКАЗЫВАЕТСЯ писать.
SHEET_HEADERS: dict[str, str] = {
    "A": "дата вход",
    "B": "время сигнала",
    "C": "токен",
    "D": "сигнал",
    "F": "цена открытия",
    "H": "дата выход",
    "I": "время выхода",
    "J": "цена закрытия",
}

# Значение столбца D. Спот: продажа — это продажа того, чего нет, поэтому
# значение ровно одно и константой оно и остаётся.
SIGNAL_TEXT_BUY = "покупать"


def _tz(timezone_name: str) -> ZoneInfo:
    """Пояс по имени. Неизвестное имя — ошибка, а не тихий откат к UTC.

    Тихий откат к UTC сдвинул бы все четыре поля времени на три часа, и лист
    разошёлся бы с сообщениями бота, оставаясь при этом правдоподобным.
    """
    return ZoneInfo(timezone_name)


def fmt_date(ts: datetime, timezone_name: str) -> str:
    """Дата в поясе отображения: ``ДД.ММ.ГГГГ``."""
    return ts.astimezone(_tz(timezone_name)).strftime("%d.%m.%Y")


def fmt_time(ts: datetime, timezone_name: str) -> str:
    """Время в поясе отображения: ``Ч:ММ:СС`` (час без ведущего нуля)."""
    local = ts.astimezone(_tz(timezone_name))
    return f"{local.hour}:{local.minute:02d}:{local.second:02d}"


def short_token(symbol: str) -> str:
    """``BTC/USDT`` → ``BTC``. В листе стоит короткое имя, а не пара."""
    return str(symbol).split("/", 1)[0]


def is_exportable(row: dict[str, Any], *, instrument_symbol: str) -> bool:
    """Годится ли позиция для записи в лист. Четыре условия, все одновременно.

    1. ПОЗИЦИЯ ЗАКРЫТА. Открытая в лист не идёт: у неё нет цены закрытия, и
       полустрока сломала бы формулы.
    2. ИНСТРУМЕНТ ТОТ САМЫЙ (см. модульный докстринг: лист моделирует один
       кошелёк, и пять слотов вперемешку дали бы доходность несуществующего
       счёта).
    3. СТРОКА ЕЩЁ НЕ ЗАПИСАНА (``sheet_exported_at IS NULL``). Признак лежит в
       базе, а не в памяти процесса: перезапуск после сбоя сети — штатное
       событие, и вторая строка той же сделки удвоила бы её прибыль во всей
       последующей цепочке G.
    4. ЕСТЬ ЧЕМ ЗАПОЛНИТЬ ОБА ПОЛЯ ВЫХОДА. Строка без цены или момента закрытия
       — это та же полустрока.
    """
    if str(row.get("status") or "") != "closed":
        return False
    if str(row.get("symbol") or "") != str(instrument_symbol):
        return False
    if row.get("sheet_exported_at") is not None:
        return False
    return row.get("closed_at") is not None and row.get("exit_price") is not None


def build_position_row(
    row: dict[str, Any], *, timezone_name: str
) -> dict[str, Any]:
    """Собирает объект строки: ключи — БУКВЫ СТОЛБЦОВ, значения — что писать.

    Ключей ровно восемь и ровно тех, что в :data:`SHEET_COLUMNS`. Это не
    формальность: объект целиком уходит приёмнику, и лишний ключ означал бы
    запись в столбец с формулой.

    Цены остаются ЧИСЛАМИ, а не строками: на них считают формулы листа, а число,
    записанное текстом, выглядит в ячейке так же и не считается никак.
    """
    opened_at = row["opened_at"]
    signal_ts = row["signal_ts"]
    closed_at = row["closed_at"]
    values: dict[str, Any] = {
        "A": fmt_date(opened_at, timezone_name),
        "B": fmt_time(signal_ts, timezone_name),
        "C": short_token(row["symbol"]),
        "D": SIGNAL_TEXT_BUY,
        "F": float(row["entry_price"]),
        "H": fmt_date(closed_at, timezone_name),
        "I": fmt_time(closed_at, timezone_name),
        "J": float(row["exit_price"]),
    }
    if tuple(values) != SHEET_COLUMNS:
        # Утверждение о самом себе: перечень столбцов и состав объекта обязаны
        # совпадать. Разойдись они — запись ушла бы в столбец с формулой, а
        # заметить это можно было бы только по сломанному листу владельца.
        raise ValueError(
            f"состав столбцов разошёлся с SHEET_COLUMNS: {tuple(values)} "
            f"вместо {SHEET_COLUMNS}"
        )
    return values


def dry_run_text(
    row: dict[str, Any] | None, *, timezone_name: str, sheet_name: str
) -> str:
    """Текст ``--dry-run`` (§7.8): что именно было бы записано, и куда.

    Печатается ДО первой настоящей записи, чтобы владелец сверил строку с листом
    глазами. Пояс называется прямым текстом: столбца с поясом в листе нет, и
    сверить его иначе не с чем.
    """
    lines = [
        "=" * 78,
        " ЧТО БЫЛО БЫ ЗАПИСАНО В ЛИСТ (--dry-run, ничего не записано)",
        "=" * 78,
        f"  Лист:            {sheet_name}",
        f"  Часовой пояс:    {timezone_name} (все четыре поля времени)",
        f"  Столбцы записи:  {', '.join(SHEET_COLUMNS)}"
        "  — и только они",
        "",
    ]
    if row is None:
        lines.append("  Закрытых позиций по этому инструменту в базе нет —")
        lines.append("  сверять нечего. Это не сбой: до первого закрытия строки")
        lines.append("  в листе не появляются по построению.")
        return "\n".join(lines)

    values = build_position_row(row, timezone_name=timezone_name)
    lines.append(f"  Позиция #{int(row['id'])} · {row['symbol']}")
    if row.get("sheet_exported_at") is not None:
        lines.append(
            f"  ⚠ уже записана в лист {row['sheet_exported_at']} — повторно "
            "не пойдёт"
        )
    lines.append("")
    lines.append(f"    {'столбец':<9}{'заголовок листа':<18}значение")
    lines.append("    " + "-" * 60)
    for column in SHEET_COLUMNS:
        lines.append(
            f"    {column:<9}{SHEET_HEADERS[column]:<18}{values[column]}"
        )
    lines.append("")
    lines.append("  Столбец G («вход - объем») и столбцы K..S НЕ ТРОГАЮТСЯ:")
    lines.append("  это формулы листа. Приёмник протягивает их в новую строку")
    lines.append("  сам и отказывается писать, если протянуть не удалось.")
    return "\n".join(lines)
