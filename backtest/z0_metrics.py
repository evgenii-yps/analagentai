"""Машиночитаемые ключи Замера 0: файл рядом с журналом, а не вместо него.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Пункт 5 ``deploy/verify_z0.sh`` читает итоги
прогонов по машиночитаемым ключам, и единственным их источником был журнал
КОНТЕЙНЕРА. Журнал вытесняется по объёму и исчезает вместе с контейнером, а
контейнер шага 14 запускается с ``--rm`` и не переживает собственного прогона.
Прогон 11.09.2026 показал это прямо: ключ ``z0_parity_ohlc_mismatches`` лежал
в журнале и находился grep-ом, а проверка печатала «⚪ НЕ ПРОВЕРЕНО».

Поэтому ключи пишутся ЕЩЁ И В ФАЙЛ в ``analysis_out/`` — каталог смонтирован с
хоста (docker-compose.yml), переживает контейнер и не вытесняется. Журнал
остаётся ЗАПАСНЫМ источником, а не единственным.

ФОРМАТ — ``ключ=значение``, по строке на ключ, ДОПИСЫВАНИЕМ. Тот же вид, в
каком ключи ищутся в журнале: один разбор на два источника вместо двух
разборов, которые однажды разойдутся. Дописывание, а не перезапись: шаги 9, 11
и 14 — разные прогоны, и затирать чужие ключи своими значило бы прятать их.
Читатель берёт ПОСЛЕДНЕЕ вхождение ключа.

ЗАПИСЬ НИКОГДА НЕ РОНЯЕТ ПРОГОН. Каталог может быть не смонтирован или
принадлежать root — это повод напечатать, куда не удалось записать, а не повод
потерять шестичасовую загрузку. Функция возвращает путь при успехе и ``None``
при неудаче, и вызывающий код печатает ровно то, что произошло.
"""

from __future__ import annotations

import os
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

# Путь по умолчанию. Каталог ``analysis_out`` смонтирован с хоста именно сюда
# (docker-compose.yml: ./analysis_out:/opt/agent-trade/analysis_out). Ключ
# окружения нужен для стенда и для тестов, где такого каталога нет.
DEFAULT_METRICS_PATH = Path("/opt/agent-trade/analysis_out/z0_metrics.txt")

# Ключ времени записи. ЧИСЛОВОЙ намеренно: он ищется тем же разбором
# ``ключ=значение``, что и остальные, и текстовая метка с двоеточиями через
# него не проходит. Нужен затем, чтобы проверка отличала свежие ключи от
# оставшихся с прошлого прогона.
EPOCH_KEY = "z0_metrics_epoch"


def metrics_path() -> Path:
    """Куда пишутся ключи. ``Z0_METRICS_PATH`` перекрывает значение по умолчанию."""
    override = os.environ.get("Z0_METRICS_PATH", "").strip()
    return Path(override) if override else DEFAULT_METRICS_PATH


def write_metrics(run: str, values: dict[str, Any]) -> Path | None:
    """Дописывает ключи прогона ``run`` в файл. ``None`` — записать не удалось.

    Исключение наружу не выпускается ни одно: потеря места для ключей не стоит
    прогона, который их добыл.
    """
    path = metrics_path()
    now = datetime.now(UTC)
    lines = [f"# {run} {now.isoformat()}"]
    lines += [f"{key}={_render(value)}" for key, value in values.items()]
    lines.append(f"{EPOCH_KEY}={int(now.timestamp())}")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
    except OSError:
        return None
    return path


def _render(value: Any) -> str:
    """Число в том виде, в каком его найдёт разбор ``[-0-9.e+]``.

    Ни пробелов, ни запятых, ни единиц измерения: значение обязано быть
    пригодным для ``awk`` без дополнительной чистки на стороне читателя.

    Для дробных берётся ``repr``: он не теряет знаков и не навязывает
    показательную запись там, где она мешает читать (``180.4``, а не
    ``1.804000e+02``). Файл ключей читает и человек тоже.
    """
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    return str(value)
