# Разбор СТРОКИ ЗАПУСКА СЛУЖБЫ, устойчивый к формату вывода журнала.
#
# ЭТО НЕ САМОСТОЯТЕЛЬНЫЙ СКРИПТ, А БИБЛИОТЕКА: подключается через ``source``
# из deploy/verify_9_3.sh. Вынесена отдельным файлом ровно затем, чтобы её
# можно было проверить тестом на настоящих строках обоих форматов — проверка
# журнала, которую нельзя прогнать, однажды перестаёт работать молча.
#
# ЗАЧЕМ ЭТО ПОНАДОБИЛОСЬ (дефект, найденный на боевом сервере 13.09.2026).
# Первая редакция §2 проверки искала величины по образцу JSON — `"logic_version": 7`
# — и брала ПОСЛЕДНЮЮ подходящую строку журнала. На бою это дало девять ложных
# тревог подряд при полностью верной конфигурации. Причин две, и обе устранены
# здесь:
#
#  1. ДВА ФОРМАТА. ``src/core/logging.py`` выбирает рендер по TTY: JSON, когда
#     stdout не терминал, и человекочитаемый ConsoleRenderer, когда терминал.
#     В журнале контейнера встречаются оба, и выглядят они по-разному:
#         JSON:    "one_per_token": false   "notify_daily_summary_utc": "06:00"
#         CONSOLE: one_per_token=False      notify_daily_summary_utc=06:00
#     Образец, написанный под один формат, на другом не находит НИЧЕГО — и
#     печатает это как «в строке запуска нет величины», то есть как поломку
#     развёртывания.
#
#  2. ДВЕ СТРОКИ ЗАПУСКА. Служба позиций печатает свои величины ДВАЖДЫ — из
#     ``src/positions_main.py`` и из ``src/positions/runner.run()``. Служба
#     уведомлений — один раз. ``tail -1`` брал ту, что оказалась последней, и
#     решение зависело от порядка, к настройкам отношения не имеющего.
#
# ЧТО СДЕЛАНО ВМЕСТО ЭТОГО. Строка приводится к одному виду — ``ключ=значение``
# в нижнем регистре, — и проверяются ВСЕ строки-кандидаты, а не последняя:
# достаточно, чтобы ХОТЯ БЫ ОДНА несла все требуемые величины. Две строки об
# одном и том же запуске не могут противоречить друг другу — они собраны одной
# функцией ``startup_fields()``.

# Убирает управляющие последовательности цвета. ``docker compose --no-color``
# гасит СВОЮ раскраску, но не раскраску ConsoleRenderer внутри строки.
strip_ansi() {
    sed -e 's/\x1B\[[0-9;]*[a-zA-Z]//g'
}

# Приводит строку журнала любого формата к виду ` ключ=значение ключ=значение `.
#
# ПОРЯДОК ЗАМЕН СОДЕРЖАТЕЛЕН. Сначала `"ключ": ` → `ключ=`, потом `="значение"`
# → `=значение`. Поменяй местами — и кавычки вокруг значения снялись бы раньше,
# чем распознан ключ, а значение вроде `06:00` распалось бы на два куска.
normalize_log_line() {
    printf ' %s ' "$1" \
        | strip_ansi \
        | sed -e 's/"\([A-Za-z_][A-Za-z0-9_]*\)"[[:space:]]*:[[:space:]]*/\1=/g' \
              -e 's/="\([^"]*\)"/=\1/g' \
              -e 's/[{},]/ /g' \
              -e 's/"/ /g' \
        | tr 'A-Z' 'a-z' \
        | tr -s ' '
}

# Несёт ли строка ВСЕ перечисленные величины. Величины задаются уже в
# каноническом виде и в нижнем регистре: `logic_version=7`, `one_per_token=false`.
#
# СРАВНЕНИЕ С ПРОБЕЛАМИ ПО КРАЯМ — не педантизм: без них `budget_usd=0` совпал
# бы с `budget_usd=0.5`, и проверка молча пропускала бы неверное значение.
line_has_fields() {
    local line="$1"; shift
    local field
    for field in "$@"; do
        case "${line}" in
            *" ${field} "*) ;;
            *) return 1 ;;
        esac
    done
    return 0
}

# Есть ли среди строк журнала хотя бы одна, несущая все величины.
#
# Возвращает 0 и печатает найденную строку; иначе возвращает 1 и печатает
# перечень величин, которых не нашлось НИ В ОДНОЙ строке, — а не в последней.
# Разница видна в выводе: «нет cooldown_sec» и «ни одна из двух строк запуска
# не содержит cooldown_sec» — разные утверждения.
find_startup_line() {
    local logs="$1"; shift
    local line normalized missing="" field found=""
    while IFS= read -r line; do
        [ -z "${line}" ] && continue
        normalized="$(normalize_log_line "${line}")"
        if line_has_fields "${normalized}" "$@"; then
            printf '%s' "${normalized}"
            return 0
        fi
        [ -z "${found}" ] && found="${normalized}"
    done <<< "${logs}"
    for field in "$@"; do
        case "${found}" in
            *" ${field} "*) ;;
            *) missing="${missing}${field} " ;;
        esac
    done
    printf '%s' "${missing}"
    return 1
}
