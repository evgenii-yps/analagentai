# Чтение слепка «ДО развёртывания» — в том числе снятого ПРЕЖНЕЙ редакцией.
#
# ЭТО НЕ САМОСТОЯТЕЛЬНЫЙ СКРИПТ, А БИБЛИОТЕКА: подключается через ``source`` из
# deploy/verify_9_3.sh. Вынесена отдельным файлом по той же причине, что и
# deploy/startup_line.sh, — чтобы её можно было прогнать тестом на настоящем
# файле слепка. Проверка, которую нельзя прогнать, однажды перестаёт работать
# молча, а этой предстоит читать файл, который больше никогда не будет снят
# заново: развёртывание состоялось, «до» невоспроизводимо.
#
# ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: слепок ПРЕЖНЕЙ редакции обязан читаться без
# ошибок. Не «желательно» — обязан. Скрипт, спотыкающийся о собственный
# вчерашний вывод, обнуляет единственное свидетельство состояния «до».

# Значение ключа из файла слепка. Отсутствующий ключ — пустая строка и код 0:
# «ключа нет» это законный ответ, а не сбой. Падать на нём значило бы уронить
# весь прогон проверки из-за величины, которой в прежней редакции не было.
snapshot_val() {
    local file="$1" key="$2"
    [ -r "${file}" ] || return 0
    grep -E "^${key}=" "${file}" 2>/dev/null | head -1 | cut -d= -f2- || true
}

# Граница времени для сверки целей (§13.1.6). Печатает две величины через
# пробел: саму границу и её ВИД. Пустая строка — границы нет вовсе.
#
# ДВА ВИДА, И ВТОРОЙ НЕ ВЫБРАСЫВАЕТСЯ.
#
#   «точная»          — ключ ``targets_boundary``, снятый с часов БАЗЫ в тот
#                       же миг, что и суммы. Сверка однозначна.
#   «восстановленная» — слепок прежней редакции: ключа границы в нём нет и
#                       появиться не может. Границей служит
#                       ``snapshot_taken_at``, снятый часами ХОСТА в начале
#                       прогона — то есть НЕСКОЛЬКО РАНЬШЕ, чем база посчитала
#                       суммы. Строка, вставленная в этот промежуток, попала в
#                       сумму, но окажется за границей.
#
# Изъян второго вида известен и потому проверяем: вызывающий обязан измерить,
# сколько строк легло вблизи границы, и отказаться от сверки, если их больше
# нуля. Сама эта функция ничего не решает — она только называет вид, чтобы
# решение принималось явно, а не по отсутствию ключа.
pick_targets_boundary() {
    local file="$1" value
    value="$(snapshot_val "${file}" targets_boundary)"
    if [ -n "${value}" ] && [ "${value}" != "НЕ_СНЯТО" ]; then
        printf '%s точная' "${value}"
        return 0
    fi
    value="$(snapshot_val "${file}" snapshot_taken_at)"
    if [ -n "${value}" ] && [ "${value}" != "НЕ_СНЯТО" ]; then
        printf '%s восстановленная' "${value}"
        return 0
    fi
    return 0
}
