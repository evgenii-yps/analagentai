#!/usr/bin/env bash
# Общий помощник скриптов проверки deploy/verify_*.sh (Этап 9.9, п. 7 ТЗ).
#
# ЗАЧЕМ. Служба пишет строку запуска в консольном формате structlog:
#     2026-10-18T13:40:21Z [info     ] Сервис demo запущен  mm_enabled=True mm_reserve_pct=25.0 ...
# а скрипты проверки искали её по образцу JSON ("mm_enabled": true) и находили «ничего»:
# ложное ❌ и «не проверено» при правильном развёртывании (итог 18.10.2026; тот же класс
# дефекта — №1 записи 13.09.2026, verify_9_3.sh). Здесь одна пара функций читает строку
# запуска В ОБОИХ форматах: `"ключ": значение` (JSON) и `ключ=значение` (консоль).
#
# Файл подключается командой ``source`` и сам ничего не выполняет, баз и контейнеров не трогает.
#
#   startup_line "<журнал>" <ключ>           последняя строка журнала с этим ключом (в любом формате)
#   startup_val  "<строка>" <ключ>           значение ключа: без кавычек, True/False → true/false
#   startup_ts   "<строка>"                  время записи строки (JSON "timestamp" или начало строки)
#   startup_eq   "<строка>" <ключ> <ожид.>   0, если значение равно ожидаемому (числа — как числа)
#
# Пустой результат функций — «нет такой строки/ключа»; вызывающий печатает его как НЕ ПРОВЕРЕНО.

# Убирает цветовые последовательности ANSI (консольный рендерер может красить ключи и значения).
_lv_strip_ansi() { sed -E $'s/\x1b\\[[0-9;]*m//g'; }

startup_line() {  # $1 — журнал целиком, $2 — ключ
    printf '%s\n' "$1" | _lv_strip_ansi \
        | grep -E "(\"$2\"[[:space:]]*:|(^|[[:space:]])$2=)" | tail -1 || true
}

startup_val() {  # $1 — строка запуска, $2 — ключ
    local line raw
    line="$(printf '%s\n' "$1" | _lv_strip_ansi)"
    raw="$(printf '%s\n' "${line}" \
        | grep -oE "\"$2\"[[:space:]]*:[[:space:]]*(\"[^\"]*\"|[^,}[:space:]]+)" | head -1 \
        | sed -E 's/^"[^"]*"[[:space:]]*:[[:space:]]*//' || true)"
    if [ -z "${raw}" ]; then
        raw="$(printf '%s\n' "${line}" \
            | grep -oE "(^|[[:space:]])$2=('[^']*'|\"[^\"]*\"|[^[:space:]]+)" | head -1 \
            | sed -E "s/^[[:space:]]*$2=//" || true)"
    fi
    raw="$(printf '%s' "${raw}" | sed -E "s/^(['\"])(.*)\\1\$/\\2/")"
    case "${raw}" in
        True|true)   printf 'true' ;;
        False|false) printf 'false' ;;
        *)           printf '%s' "${raw}" ;;
    esac
}

startup_ts() {  # $1 — строка запуска
    local ts
    ts="$(startup_val "$1" timestamp)"
    if [ -z "${ts}" ]; then
        ts="$(printf '%s\n' "$1" | _lv_strip_ansi \
            | grep -oE '[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9:.]+(Z|[+-][0-9]{2}:?[0-9]{2})?' \
            | head -1 || true)"
    fi
    printf '%s' "${ts}"
}

startup_eq() {  # $1 — строка, $2 — ключ, $3 — ожидаемое значение
    local got
    got="$(startup_val "$1" "$2")"
    [ -n "${got}" ] || return 1
    local num='^-?[0-9]+([.][0-9]+)?$'
    if [[ "${got}" =~ ${num} && "$3" =~ ${num} ]]; then
        awk -v a="${got}" -v b="$3" 'BEGIN { exit !(a + 0 == b + 0) }'
    else
        [ "${got}" = "$3" ]
    fi
}
